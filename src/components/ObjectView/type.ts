export interface ObjectViewProps {
  /** Будь-яке значення, яке треба показати. Зазвичай об'єкт або масив. */
  data: unknown;
  /** Опціональна підпис-мітка для кореня (наприклад, ім'я змінної). */
  name?: string;
  className?: string;
  /**
   * Якщо явно `=== true`, всі вкладені вузли (об'єкти, масиви, Map, Set, функції з
   * доступним сирцем) за замовчуванням розгорнуті. У будь-якому іншому випадку
   * (включно з `undefined`) — згорнуті, як звичайно.
   */
  defaultExpanded?: boolean;
}
